 await page.getByRole('button',{name:'上传并上图',exact:true}).click()
 await expect(page.locator('#dialog')).toBeHidden()
 await expect(page.locator('.mw-owned-layers')).toContainText('浏览器上传与分析')
 await expect(page.locator('.leaflet-overlay-pane path.leaflet-interactive')).toHaveCount(2)
 await page.goto('/#/vector')
 await page.getByLabel('用户图层').selectOption({label:'浏览器上传与分析 · 2要素'})
 await page.getByRole('button',{name:'运行分析',exact:true}).click()
